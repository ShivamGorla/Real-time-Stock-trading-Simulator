package com.stocktrading.simulator.assistant.config;

import com.stocktrading.simulator.assistant.client.exception.LlmConfigurationException;
import org.springframework.boot.context.properties.ConfigurationProperties;

import java.time.Duration;

/**
 * Type-safe configuration properties for the StockSim AI Trading Assistant.
 * Bound to prefix {@code stocksim.assistant}.
 */
@ConfigurationProperties(prefix = "stocksim.assistant")
public class AssistantProperties {

    /**
     * Whether the AI Assistant module is enabled. Defaults to false.
     */
    private boolean enabled = false;

    /**
     * Base URL for the OpenAI-compatible Chat Completions API endpoint. Defaults to Groq API.
     */
    private String baseUrl = "https://api.groq.com/openai/v1";

    /**
     * API key for provider authentication. Must be supplied when enabled is true.
     */
    private String apiKey;

    /**
     * Model identifier to request (configured via STOCKSIM_ASSISTANT_MODEL; defaults to a provider-supported Groq model).
     */
    private String model = "llama-3.3-70b-versatile";

    /**
     * Sampling temperature between 0.0 and 2.0. Defaults to 0.1 for high determinism.
     */
    private Double temperature = 0.1;

    /**
     * Maximum completion tokens generated by the model per turn.
     */
    private Integer maxTokens = 1024;

    /**
     * HTTP connection establishment timeout.
     */
    private Duration connectTimeout = Duration.ofSeconds(5);

    /**
     * HTTP response read timeout.
     */
    private Duration readTimeout = Duration.ofSeconds(30);

    /**
     * Validates configuration settings when enabled is true.
     *
     * @throws LlmConfigurationException if enabled is true but required properties are missing
     */
    public void validate() {
        if (!enabled) {
            return;
        }
        if (apiKey == null || apiKey.trim().isEmpty()) {
            throw new LlmConfigurationException(
                "StockSim AI Assistant is enabled (stocksim.assistant.enabled=true), but 'stocksim.assistant.api-key' is missing or blank. " +
                "Provide a valid API key via environment variable (STOCKSIM_ASSISTANT_API_KEY) or property."
            );
        }
        if (baseUrl == null || baseUrl.trim().isEmpty()) {
            throw new LlmConfigurationException(
                "StockSim AI Assistant is enabled, but 'stocksim.assistant.base-url' is missing or blank."
            );
        }
        if (model == null || model.trim().isEmpty()) {
            throw new LlmConfigurationException(
                "StockSim AI Assistant is enabled, but 'stocksim.assistant.model' is missing or blank."
            );
        }
        if (temperature != null && (temperature < 0.0 || temperature > 2.0)) {
            throw new LlmConfigurationException("stocksim.assistant.temperature must be between 0.0 and 2.0");
        }
        if (maxTokens != null && maxTokens <= 0) {
            throw new LlmConfigurationException("stocksim.assistant.max-tokens must be strictly positive");
        }
    }

    public boolean isEnabled() {
        return enabled;
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
    }

    public String getBaseUrl() {
        return baseUrl;
    }

    public void setBaseUrl(String baseUrl) {
        this.baseUrl = baseUrl;
    }

    public String getApiKey() {
        return apiKey;
    }

    public void setApiKey(String apiKey) {
        this.apiKey = apiKey;
    }

    public String getModel() {
        return model;
    }

    public void setModel(String model) {
        this.model = model;
    }

    public Double getTemperature() {
        return temperature;
    }

    public void setTemperature(Double temperature) {
        this.temperature = temperature;
    }

    public Integer getMaxTokens() {
        return maxTokens;
    }

    public void setMaxTokens(Integer maxTokens) {
        this.maxTokens = maxTokens;
    }

    public Duration getConnectTimeout() {
        return connectTimeout;
    }

    public void setConnectTimeout(Duration connectTimeout) {
        this.connectTimeout = connectTimeout;
    }

    public Duration getReadTimeout() {
        return readTimeout;
    }

    public void setReadTimeout(Duration readTimeout) {
        this.readTimeout = readTimeout;
    }

    /**
     * Safe string representation that masks credentials.
     */
    @Override
    public String toString() {
        return "AssistantProperties{" +
                "enabled=" + enabled +
                ", baseUrl='" + baseUrl + '\'' +
                ", apiKey=" + (apiKey != null && !apiKey.isBlank() ? "'***'" : "null") +
                ", model='" + model + '\'' +
                ", temperature=" + temperature +
                ", maxTokens=" + maxTokens +
                ", connectTimeout=" + connectTimeout +
                ", readTimeout=" + readTimeout +
                '}';
    }
}
