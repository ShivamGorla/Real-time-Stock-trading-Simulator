package com.stocktrading.simulator.assistant.tool;

import com.stocktrading.simulator.assistant.client.model.ToolDefinition;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import java.util.*;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Strict allowlisted registry for all AI Assistant tools.
 *
 * <p><strong>Security Invariants:</strong></p>
 * <ul>
 *   <li>Only explicitly registered {@link AssistantTool} implementations can be retrieved or executed.</li>
 *   <li>Duplicate tool names are rejected fail-fast during registration.</li>
 *   <li>Execution injects the server-side authenticated username, preventing user identity spoofing.</li>
 *   <li>Tool exceptions are caught and returned as controlled error results without leaking sensitive infrastructure details.</li>
 * </ul>
 */
@Component
public class ToolRegistry {

    private static final Logger log = LoggerFactory.getLogger(ToolRegistry.class);

    private final Map<String, AssistantTool> toolsMap = new ConcurrentHashMap<>();

    public ToolRegistry(List<AssistantTool> tools) {
        if (tools != null) {
            for (AssistantTool tool : tools) {
                registerTool(tool);
            }
        }
        log.info("Initialized ToolRegistry with {} tools: {}", toolsMap.size(), toolsMap.keySet());
    }

    /**
     * Registers a new tool into the allowlist.
     *
     * @param tool the tool implementation to register
     * @throws IllegalStateException if a tool with the same name is already registered
     */
    public synchronized void registerTool(AssistantTool tool) {
        if (tool == null) {
            throw new IllegalArgumentException("Cannot register null tool");
        }
        String name = tool.getName();
        if (name == null || name.isBlank()) {
            throw new IllegalArgumentException("Tool name cannot be null or blank");
        }
        if (toolsMap.containsKey(name)) {
            throw new IllegalStateException("Duplicate tool registration detected for tool name: '" + name + "'");
        }
        toolsMap.put(name, tool);
        log.debug("Registered assistant tool: '{}'", name);
    }

    /**
     * Retrieves an AssistantTool by name if registered.
     */
    public Optional<AssistantTool> getTool(String name) {
        if (name == null) {
            return Optional.empty();
        }
        return Optional.ofNullable(toolsMap.get(name));
    }

    /**
     * Checks whether a tool name is registered in the allowlist.
     */
    public boolean hasTool(String name) {
        return name != null && toolsMap.containsKey(name);
    }

    /**
     * Returns the unmodifiable set of all registered tool names.
     */
    public Set<String> getRegisteredToolNames() {
        return Collections.unmodifiableSet(new TreeSet<>(toolsMap.keySet()));
    }

    /**
     * Returns the count of registered tools.
     */
    public int getToolCount() {
        return toolsMap.size();
    }

    /**
     * Returns OpenAPI/JSON schema specifications for all registered tools,
     * suitable for inclusion directly in a {@code ChatCompletionRequest}.
     */
    public List<ToolDefinition> getToolDefinitions() {
        return toolsMap.values().stream()
                .map(AssistantTool::getToolDefinition)
                .toList();
    }

    /**
     * Safely executes an allowlisted tool using server-injected user context.
     *
     * @param toolName      the name of the tool to execute
     * @param username      the authenticated username provided by Spring Security
     * @param argumentsJson the JSON arguments string generated by the LLM
     * @return structured {@link ToolResult}
     */
    public ToolResult executeTool(String toolName, String username, String argumentsJson) {
        if (toolName == null || toolName.isBlank()) {
            return ToolResult.error("Tool name cannot be null or blank");
        }
        if (username == null || username.isBlank()) {
            return ToolResult.error("Authenticated username is required for tool execution");
        }

        AssistantTool tool = toolsMap.get(toolName);
        if (tool == null) {
            log.warn("Attempted execution of unregistered tool '{}' by user '{}'", toolName, username);
            return ToolResult.error("Unknown tool: '" + toolName + "'. Available tools: " + getRegisteredToolNames());
        }

        log.debug("Executing tool '{}' for user '{}'", toolName, username);
        try {
            return tool.execute(username, argumentsJson);
        } catch (Exception ex) {
            log.error("Unhandled exception executing tool '{}' for user '{}': {}", toolName, username, ex.getClass().getSimpleName());
            return ToolResult.error("Unable to complete tool '" + toolName + "' due to an internal error.");
        }
    }
}
